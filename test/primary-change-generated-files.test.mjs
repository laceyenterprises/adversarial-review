import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { checkPrimaryChange, fetchPrimaryChange } from '../src/ama/primary-change.mjs';
import { proveGeneratedBlocks } from '../src/ama/derived-artifacts.mjs';

const header = 'Generated by `node render.mjs --write`; definitions are the source.';
const path = 'docs/states.md';

function fixture(t, { generatorHeader = header, finalHeader = generatorHeader, primaryHeader = generatorHeader, baseHeader = generatorHeader,
  handEdit = false, revertSource = false, finalNewline = true, addedRow = false } = {}) {
  const root = mkdtempSync(join(tmpdir(), 'derived-file-fixture-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8', timeout: 5000,
    env: { ...process.env, GIT_CONFIG_NOSYSTEM: '1', GIT_CONFIG_GLOBAL: '/dev/null',
      GIT_AUTHOR_NAME: 'Fixture Builder', GIT_AUTHOR_EMAIL: 'builder@example.invalid',
      GIT_COMMITTER_NAME: 'Fixture Builder', GIT_COMMITTER_EMAIL: 'builder@example.invalid' } }).trimEnd();
  const output = (count, declaration) => `${declaration}\n| States | Edges |\n| sample | ${count} |${finalNewline ? '\n' : ''}`;
  git('init', '-q');
  mkdirSync(join(root, 'docs'));
  writeFileSync(join(root, 'definitions.txt'), '40\nbase transition');
  writeFileSync(join(root, 'render.mjs'), `
import fs from 'node:fs';
const header = ${JSON.stringify(generatorHeader)};
const count = fs.readFileSync('definitions.txt', 'utf8').split('\\n')[0];
fs.writeFileSync(${JSON.stringify(path)}, header + '\\n| States | Edges |\\n| sample | ' + count + ' |'
  + ${JSON.stringify(finalNewline ? '\n' : '')});
`);
  writeFileSync(join(root, path), output(42, baseHeader));
  git('add', 'definitions.txt', 'render.mjs', path);
  git('commit', '-qm', 'Fixture base');
  const mergeBase = git('rev-parse', 'HEAD');
  writeFileSync(join(root, 'definitions.txt'), '42\nauthor transition');
  writeFileSync(join(root, path), output(37, primaryHeader) + (addedRow ? '\nStale generated footer\n' : ''));
  git('add', 'definitions.txt', path);
  git('commit', '-qm', 'Fixture author with stale output');
  const primaryHead = git('rev-parse', 'HEAD');
  writeFileSync(join(root, 'definitions.txt'), revertSource ? '42\nbase transition' : '42\nauthor transition');
  writeFileSync(join(root, path), output(42, finalHeader)
    .replace('| States |', handEdit ? '| Hand edited |' : '| States |'));
  git('add', 'definitions.txt', path);
  git('commit', '-qm', 'Fixture repair\n\nWorker-Class: hammer');
  const headSha = git('rev-parse', 'HEAD');
  const files = to => git('diff', '--name-only', mergeBase, to).split('\n').filter(Boolean).map(filename => {
    const lines = git('diff', '--no-ext-diff', '--unified=3', mergeBase, to, '--', filename).split('\n');
    const body = lines.slice(lines.findIndex(line => line.startsWith('@@ ')));
    return { filename, status: 'modified', patch: body.join('\n'),
      additions: body.filter(line => line.startsWith('+')).length,
      deletions: body.filter(line => line.startsWith('-')).length };
  });
  const evidence = { headSha, mergeBase, primaryHead, hasHammerCommits: true,
    ciCost: { headSha, ok: true }, primaryFiles: files(primaryHead), finalFiles: files(headSha) };
  const get = async url => {
    if (url.endsWith('/pulls/1')) return { head: { sha: headSha }, base: { sha: mergeBase } };
    if (url.endsWith(`${mergeBase}...${headSha}`)) return { files: evidence.finalFiles,
      merge_base_commit: { sha: mergeBase }, total_commits: 2, commits: [
        { sha: primaryHead, commit: { message: 'Fixture author with stale output' } },
        { sha: headSha, parents: [{ sha: primaryHead }], commit: { message: 'Fixture repair\n\nWorker-Class: hammer' } },
      ] };
    if (url.endsWith(`${mergeBase}...${primaryHead}`)) return { files: evidence.primaryFiles,
      merge_base_commit: { sha: mergeBase } };
    if (url.includes('/reviews') || url.includes('/comments')) return [];
    if (url.endsWith(`/commits/${headSha}`)) return { sha: headSha, files: evidence.finalFiles };
    throw new Error(`Unexpected offline fixture read: ${url}`);
  };
  return { root, evidence, args: { repo: 'fixture/repository', prNumber: 1, headSha, get, localRepository: root } };
}

const offlineGenerator = async ({ scratch, cwd, command }) => {
  assert.deepEqual(command, ['node', 'render.mjs', '--write']);
  assert.throws(() => readFileSync(join(scratch, cwd, path)), { code: 'ENOENT' }, 'output must be removed before proof');
  execFileSync(process.execPath, command.slice(1), { cwd: join(scratch, cwd), timeout: 5000,
    env: { PATH: '/usr/bin:/bin', HOME: scratch } });
};

async function prove(f, runGeneratorImpl = offlineGenerator) {
  const refusal = checkPrimaryChange(f.evidence, f.args.headSha);
  assert.equal(refusal.reason, 'primary-change-reverted');
  const generatedBlockProofs = await proveGeneratedBlocks(f.args, f.evidence, refusal, { runGeneratorImpl });
  return { ...f.evidence, generatedBlockProofs };
}

test('GENERATEDPRIMARY-01: stale whole-file count regenerates from final sources without a manifest', async t => {
  for (const options of [{}, { finalNewline: false, addedRow: true }, { baseHeader: 'An older generated header' }]) {
    const f = fixture(t, options);
    assert.equal(f.evidence.finalFiles.some(file => file.filename === path), Boolean(options.baseHeader));
    const result = await prove(f);
    assert.equal(result.generatedBlockProofs.length, 1);
    assert.equal(checkPrimaryChange(result, f.args.headSha).ok, true);
    for (const field of ['primaryHead', 'headSha', 'mergeBase']) {
      const stale = structuredClone(result);
      stale[field] = 'f'.repeat(40);
      assert.equal(checkPrimaryChange(stale, stale.headSha).ok, false, `proof must bind ${field}`);
    }
  }
});

test('shared collection uses the whole-file proof and keeps generator source changes protected', async t => {
  const options = {
    fetchCiCostImpl: async args => ({ headSha: args.headSha, ok: true }),
    proveGeneratedBlocksImpl: (args, evidence, refusal) => proveGeneratedBlocks(args, evidence, refusal,
      { runGeneratorImpl: offlineGenerator }),
  };
  const f = fixture(t);
  const result = await fetchPrimaryChange(f.args, options);
  assert.equal(result.generatedBlockProofs.length, 1);
  assert.equal(checkPrimaryChange(result, f.args.headSha).ok, true);
  const reverted = fixture(t, { revertSource: true });
  // Evaluate the generated output first so its valid proof cannot mask the
  // separately reverted source declaration.
  reverted.evidence.primaryFiles.sort((left, right) => left.filename === path ? -1 : right.filename === path ? 1 : 0);
  const refused = await fetchPrimaryChange(reverted.args, options);
  assert.equal(refused.generatedBlockProofs.length, 1);
  assert.equal(checkPrimaryChange(refused, reverted.args.headSha).reason, 'primary-change-reverted');
  assert.equal(checkPrimaryChange(refused, reverted.args.headSha).path, 'definitions.txt');
});

test('recognizes a module generator and early Markdown/comment headers without a shell', async t => {
  for (const generatorHeader of [
    header.replace('node render.mjs', 'python3 -m sample.render'),
    `# ${header}`, `<!-- ${header} -->`, `\n\n${header}`,
  ]) {
    const f = fixture(t, { generatorHeader });
    const result = await prove(f, args => {
      assert.deepEqual(args.command, generatorHeader.includes('python3')
        ? ['python3', '-m', 'sample.render', '--write'] : ['node', 'render.mjs', '--write']);
      // Synthetic stub emits the declared generator's complete fixture output.
      return offlineGenerator({ ...args, command: ['node', 'render.mjs', '--write'] });
    });
    assert.equal(result.generatedBlockProofs.length, 1);
    assert.equal(checkPrimaryChange(result, result.headSha).ok, true);
  }
});

for (const [name, options] of Object.entries({
  'hand edit': { handEdit: true },
  'removed header': { finalHeader: '' },
  'changed header command': { finalHeader: header.replace('render.mjs', 'other.mjs') },
  'changed header prose': { finalHeader: header.replace('source.', 'authority.') },
  'header introduced only at final head': { primaryHeader: '' },
  'shell expansion': { primaryHeader: header.replace('--write', '$(echo --write)'), finalHeader: header.replace('--write', '$(echo --write)') },
})) {
  test(`${name} retains whole-file preservation refusal`, async t => {
    const result = await prove(fixture(t, options));
    assert.deepEqual(result.generatedBlockProofs, []);
    assert.equal(checkPrimaryChange(result, result.headSha).reason, 'primary-change-reverted');
  });
}

for (const failure of ['generator unavailable', 'generator timed out', 'network-denied generator sandbox unavailable']) {
  test(`${failure} fails closed`, async t => {
    t.mock.method(console, 'warn', () => {});
    const result = await prove(fixture(t), async () => { throw new Error(failure); });
    assert.deepEqual(result.generatedBlockProofs, []);
    assert.equal(checkPrimaryChange(result, result.headSha).reason, 'primary-change-reverted');
  });
}

test('a no-op generator cannot reuse the final whole-file output', async t => {
  t.mock.method(console, 'warn', () => {});
  const result = await prove(fixture(t), async () => {});
  assert.deepEqual(result.generatedBlockProofs, []);
  assert.equal(checkPrimaryChange(result, result.headSha).reason, 'primary-change-reverted');
});
