// REVIEWGUARD-01: read the repository's generated-index guard as data, never execute it.
import * as yaml from 'js-yaml';
import { fetchRepoFileAtRef } from './pack-lockhash.mjs';
import { execGhWithRetry } from './gh-cli.mjs';
import { parseBlockingFindingsSection, parseNonBlockingFindingsSection } from './kernel/review-findings.mjs';

const WORKFLOW = '.github/workflows/repo-guards.yml';
const GUARD = 'scripts/check-generated-index-pr-diff.py';

export const GUARD_POLICY_INSTRUCTIONS = `REVIEWGUARD-01: This plan reads generated paths and check names from the repository guard configuration at the live PR base SHA. Never recommend editing those paths; they are regenerated by automation.
In strict non-blocking remediation, each resolved finding is resolved by policy: do not edit the generated file, do not raise an operator decision, and do not invoke the blocking-only dispute helper. Copy auditDetails into HAM_AUDIT_DETAILS_FILE, retaining each exact finding title and non-blocking class. Count these policy resolutions in Remediated-Findings. Include one audit line per guard/path in the HAM terminal-remediation audit:
Resolved-By-Policy: guard:<check name> forbids <path>
Then continue to the predicate. Blocking findings keep the current remediation/dispute behaviour. In strict mode, every remaining finding still requires normal remediation. Unknown or unreadable policy and mixed remedies grant no policy resolution. Never infer a policy match from the File field alone or an author assertion. A failed helper read leaves all findings unresolved.
If every required finding is resolved by policy, no code edit or empty HAM commit is needed. Publish the head-bound audit and perform the existing exact-head validation, required checks, predicate and lease-protected merge. These policy resolutions do not waive any merge safety gate.`;

function safePath(value) {
  return typeof value === 'string' && /^[\w.-]+(?:\/[\w.-]+)*$/.test(value)
    && !value.split('/').some(part => part === '.' || part === '..');
}

async function resolveGuardBaseRef(repo, baseRef) {
  const { stdout } = await execGhWithRetry({
    args: ['api', `repos/${repo}/commits/${encodeURIComponent(baseRef)}`, '--jq', '.sha'], timeoutMs: 15_000,
  });
  return stdout.trim();
}

export async function loadGuardForbiddenPaths({ repo, baseRef, fetchFileImpl = fetchRepoFileAtRef,
  resolveRefImpl = resolveGuardBaseRef, log = console } = {}) {
  if (!repo || !baseRef) return [];
  try {
    // Pin both reads to one base commit, even when the review context only has
    // the base branch name. Never read the PR head's guard configuration.
    if (!/^[a-f0-9]{40}$/i.test(baseRef)) {
      baseRef = await resolveRefImpl(repo, baseRef);
      if (!/^[a-f0-9]{40}$/i.test(baseRef)) throw new Error('guard base SHA is missing or malformed');
    }
    const workflow = yaml.load(await fetchFileImpl(repo, WORKFLOW, baseRef));
    const checks = Object.values(workflow?.jobs || {})
      .filter(job => job?.['continue-on-error'] === undefined || job['continue-on-error'] === false)
      .flatMap(job => job?.steps || [])
      .filter(step => (step?.['continue-on-error'] === undefined || step['continue-on-error'] === false) && typeof step?.name === 'string'
        && !/[\r\n]/.test(step.name)
        && new RegExp(`(?:^|\\n)\\s*python3?\\s+${GUARD.replaceAll('.', '\\.')}(?:[\\s\\\\]|$)`).test(step.run || ''));
    if (!checks.length) return [];
    const script = await fetchFileImpl(repo, GUARD, baseRef);
    // Only a literal tuple/list is supported. Computed expressions remain unknown.
    const assignment = /^GENERATED_PATHS\s*=\s*(\(|\[)([\s\S]*?)(\)|\])\s*$/m.exec(script);
    if (!assignment || (assignment[1] === '(' ? assignment[3] !== ')' : assignment[3] !== ']')) return [];
    const literal = assignment[2];
    const string = '(?:"[\\w./-]+"|\'[\\w./-]+\')';
    if (!new RegExp(`^\\s*${string}(?:\\s*,\\s*${string})*\\s*,?\\s*$`).test(literal)) return [];
    const paths = [...literal.matchAll(/["']([^"']+)["']/g)].map(match => match[1]);
    if (assignment[1] === '(' && paths.length === 1 && !/,\s*$/.test(literal)) return [];
    if (!paths.every(safePath)) return [];
    return [...new Map(checks.flatMap(step => paths.map(path => ({ check: step.name, path })))
      .map(guard => [`${guard.check}:${guard.path}`, guard])).values()];
  } catch (error) {
    if (!/HTTP\s+404|not found/i.test(`${error?.message} ${error?.stderr || ''}`)) {
      log?.warn?.(`[reviewer] guard-forbidden policy unavailable; retaining findings: ${error?.message || error}`);
    }
    return [];
  }
}

export function formatGuardForbiddenPaths(guards = []) {
  if (!guards.length) return '';
  return '\n\nGuard-forbidden generated paths (repository base configuration):\n'
    + guards.map(({ check, path }) => `- ${check} forbids \`${path}\`.`).join('\n')
    + '\nNever recommend editing these paths; they are regenerated by automation.\n';
}

// Deliberately conservative: a complete edit-only remedy with explicit paths is
// required. A File field alone, prose about a guard, or an additional action
// cannot resolve a finding. Unknown wording stays on the remediation path.
export function guardOnlyRemedy(finding, guards = []) {
  let fix = String(finding?.recommendedFix || '').trim();
  if (!fix || !/\b(?:commit|regenerate|generate|update|edit|add|include)\b/i.test(fix)) return null;
  const matches = [];
  const paths = (fix.match(/(?:[\w.-]+\/)+[\w.-]+|[\w-]+\.[A-Za-z][\w.-]*/g) || [])
    .map(path => path.replace(/\.+$/, ''));
  if (!paths.length) return null;
  for (const path of paths) {
    const guard = guards.find(entry => entry.path === path);
    if (!guard) return null;
    matches.push(guard);
    fix = fix.replace(path, ' GUARDED_PATH ');
  }
  const verb = '(?:regenerate|generate|update|edit|add|include|commit)';
  const nouns = '(?:(?:the|this|these|generated|regenerated|updated|file|files|index|indexes|documentation|catalog|output|outputs)\\s+)*';
  const objects = `${nouns}GUARDED_PATH(?:\\s*(?:,|and)\\s*${nouns}GUARDED_PATH)*`;
  const clause = `${verb}(?:\\s+(?:and|then)\\s+${verb})*\\s+${objects}`
    + '(?:\\s+(?:in|into|for|to)\\s+(?:the\\s+)?(?:PR|pull request|commit))?'
    + '(?:\\s+(?:and|then)\\s+commit\\s+(?:it|them))?';
  const editOnly = new RegExp(`^(?:please\\s+)?(?:(?:just|only)\\s+)?${clause}(?:\\s*(?:and|then|[.;])\\s*${clause})*[.!]?$`, 'i');
  if (!editOnly.test(fix.replace(/[`'"()]/g, '').replace(/\s+/g, ' ').replace(/\s+([.,;!?])/g, '$1').trim())) return null;
  return [...new Map(matches.map(guard => [guard.path, guard])).values()];
}

function findingBlocks(section) {
  const lines = section.split('\n');
  if (lines.some(line => /^\s*(?:```|~~~)/.test(line))) return null;
  const h3 = lines.some(line => /^###\s+/.test(line));
  const hasLegacyTitles = lines.some(line => /^-[ \t]+Title[ \t]*:/i.test(line));
  const boundary = h3 ? /^###\s+/ : hasLegacyTitles ? /^-[ \t]+Title[ \t]*:/i
    : /^(?:-\s+\*\*(?!(?:Category|File|Lines|Problem|Why it matters|Recommended fix)(?::\*\*|\*\*\s*:))|-[ \t]+File[ \t]*:)/i;
  const blocks = [];
  for (const line of lines) {
    if (boundary.test(line)) blocks.push([]);
    if (blocks.length) blocks.at(-1).push(line);
    else if (line.trim()) return null;
  }
  return blocks;
}

function transformSections(text, transform) {
  const sections = [{ start: 0, bodyStart: 0 }];
  let offset = 0;
  let fence = null;
  for (const line of text.split('\n')) {
    const marker = /^\s*(`{3,}|~{3,})/.exec(line)?.[1];
    if (marker) {
      if (!fence) fence = marker;
      else if (marker[0] === fence[0] && marker.length >= fence.length) fence = null;
    } else if (!fence && /^##[ \t]+/.test(line)) {
      sections.push({ start: offset, bodyStart: Math.min(text.length, offset + line.length + 1) });
    }
    offset += line.length + 1;
  }
  return sections.map((section, index) => {
    const heading = text.slice(section.start, section.bodyStart);
    const body = text.slice(section.bodyStart, sections[index + 1]?.start ?? text.length);
    return heading ? transform(heading, body) : body;
  }).join('');
}

function completeCard(block) {
  let fieldIndent = 0;
  const seen = new Set();
  for (const line of block.slice(1)) {
    if (!line.trim()) continue;
    const indent = line.match(/^\s*/)[0].length;
    const field = /^\s*(?:-\s+)?(?:\*\*)?(Category|File|Lines|Problem|Why it matters|Recommended fix)(?::|\*\*\s*:)/i.exec(line)?.[1].toLowerCase();
    if (field) {
      if (seen.has(field)) return false;
      seen.add(field);
      fieldIndent = indent;
    } else if (indent <= fieldIndent) return false;
  }
  return true;
}

export function filterGuardForbiddenFindings(reviewText, guards = [], { log = console } = {}) {
  if (!guards.length) return reviewText;
  const dropped = [];
  let result = transformSections(String(reviewText), (heading, section) => {
    const whole = heading + section;
    if (!/^##[ \t]+(?:Blocking|Non[- \t]+blocking)[ \t]+Issues?[ \t]*\r?\n?$/i.test(heading)) return whole;
    const blocks = findingBlocks(section);
    if (!blocks?.length) return whole;
    const kept = blocks.filter(block => {
      const parsed = parseBlockingFindingsSection(`## Blocking issues\n${block.join('\n')}`);
      if (!completeCard(block) || parsed?.length !== 1 || !guardOnlyRemedy(parsed[0], guards)) return true;
      dropped.push(parsed[0].title || parsed[0].file);
      return false;
    });
    return `${heading}\n${kept.length ? kept.map(block => block.join('\n').trimEnd()).join('\n') : '- None.'}\n\n`;
  });
  if (!dropped.length) return reviewText;
  // Suggested-fix bullets can repeat a removed recommendation outside its card.
  result = transformSections(result, (heading, section) => {
    if (!/^##[ \t]+Suggested fixes[ \t]*\r?\n?$/i.test(heading)) return heading + section;
    const lines = section.split('\n').filter(line => !guardOnlyRemedy({ recommendedFix: line.replace(/^[-*]\s+/, '') }, guards));
    return heading + (lines.some(line => line.trim()) ? lines.join('\n') : '\n- None.\n\n');
  });
  const blocking = parseBlockingFindingsSection(result);
  if (blocking?.length === 0) {
    result = transformSections(result, (heading, section) => (
      /^##[ \t]+Verdict[ \t]*\r?\n?$/i.test(heading) && /^\s*Request changes\s*$/i.test(section)
        ? heading + '\nComment only\n\n' : heading + section
    ));
  }
  log?.info?.(`[reviewer] guard-forbidden findings dropped: ${JSON.stringify([...new Set(dropped)])}`);
  return result;
}

export function resolveGuardForbiddenNonBlocking(reviewText, guards = [], { strictNonBlockingRemediation = true } = {}) {
  const resolved = [];
  const nonBlocking = parseNonBlockingFindingsSection(reviewText);
  let rawSection;
  transformSections(String(reviewText), (heading, body) => {
    if (rawSection === undefined && /^##[ \t]+Non[- \t]+blocking[ \t]+Issues?[ \t]*\r?\n?$/i.test(heading)) rawSection = body;
    return heading + body;
  });
  const blocks = rawSection === undefined ? null : findingBlocks(rawSection);
  const complete = blocks && nonBlocking && blocks.length === nonBlocking.length
    ? blocks.map(block => completeCard(block) && parseNonBlockingFindingsSection(`## Non-blocking issues\n${block.join('\n')}`)?.length === 1)
    : [];
  const remaining = [];
  for (const [index, finding] of (nonBlocking || []).entries()) {
    const matched = strictNonBlockingRemediation && complete[index] && guardOnlyRemedy(finding, guards);
    if (!matched) { remaining.push(finding); continue; }
    const auditLines = matched.map(({ check, path }) => `Resolved-By-Policy: guard:${check} forbids ${path}`);
    resolved.push({ ...finding, blocking: false, addressed: true, guards: matched, auditLines });
  }
  const auditDetails = resolved.map(finding =>
    `- **${finding.title}** (non-blocking) — resolved by policy; ${finding.guards.map(guard => guard.path).join(', ')} is regenerated by automation.`);
  auditDetails.push(...new Set(resolved.flatMap(finding => finding.auditLines)));
  return { instructions: GUARD_POLICY_INSTRUCTIONS, resolved, remaining: nonBlocking === null ? null : remaining,
    blocking: parseBlockingFindingsSection(reviewText), auditDetails: auditDetails.join('\n') };
}
