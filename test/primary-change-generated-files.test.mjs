const header = 'Generated by `node render.mjs --write`; definitions are the source.';
const path = 'docs/states.md';

function fixture(t, { generatorHeader = header, finalHeader = generatorHeader, primaryHeader = generatorHeader, baseHeader = generatorHeader,
  handEdit = false, revertSource = false, finalNewline = true, addedRow = false, manifest,
  outputPath = path, generatorPath = 'render.mjs' } = {}) {
  const root = mkdtempSync(join(tmpdir(), 'derived-file-fixture-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8', timeout: 5000,
    env: { ...process.env, GIT_CONFIG_NOSYSTEM: '1', GIT_CONFIG_GLOBAL: '/dev/null',
      GIT_AUTHOR_NAME: 'Fixture Builder', GIT_AUTHOR_EMAIL: 'builder@example.invalid',
      GIT_COMMITTER_NAME: 'Fixture Builder', GIT_COMMITTER_EMAIL: 'builder@example.invalid' } }).trimEnd();
  const output = (count, declaration) => `${declaration}\n| States | Edges |\n| sample | ${count} |${finalNewline ? '\n' : ''}`;
  git('init', '-q');
  mkdirSync(dirname(join(root, outputPath)), { recursive: true });
  mkdirSync(dirname(join(root, generatorPath)), { recursive: true });
  writeFileSync(join(root, 'definitions.txt'), '40\nbase transition');
  writeFileSync(join(root, generatorPath), generatorPath.endsWith('.py') ? `
from pathlib import Path
header = ${JSON.stringify(generatorHeader)}
count = Path('definitions.txt').read_text().splitlines()[0]
Path(${JSON.stringify(outputPath)}).write_text(header + '\\n| States | Edges |\\n| sample | ' + count + ' |' + ${JSON.stringify(finalNewline ? '\n' : '')})
` : `
import fs from 'node:fs';
const header = ${JSON.stringify(generatorHeader)};
const count = fs.readFileSync('definitions.txt', 'utf8').split('\\n')[0];
fs.writeFileSync(${JSON.stringify(outputPath)}, header + '\\n| States | Edges |\\n| sample | ' + count + ' |'
  + ${JSON.stringify(finalNewline ? '\n' : '')});
`);
  writeFileSync(join(root, outputPath), output(42, baseHeader));
  if (manifest !== undefined) {
    writeFileSync(join(root, 'package.json'), manifest);
    git('add', 'package.json');
  }
  git('add', 'definitions.txt', generatorPath, outputPath);
  git('commit', '-qm', 'Fixture base');
  const mergeBase = git('rev-parse', 'HEAD');
  writeFileSync(join(root, 'definitions.txt'), '42\nauthor transition');
  writeFileSync(join(root, outputPath), output(37, primaryHeader) + (addedRow ? '\nStale generated footer\n' : ''));
  git('add', 'definitions.txt', outputPath);
  git('commit', '-qm', 'Fixture author with stale output');
  const primaryHead = git('rev-parse', 'HEAD');
  writeFileSync(join(root, 'definitions.txt'), revertSource ? '42\nbase transition' : '42\nauthor transition');
  writeFileSync(join(root, outputPath), output(42, finalHeader)
    .replace('| States |', handEdit ? '| Hand edited |' : '| States |'));
  git('add', 'definitions.txt', outputPath);
  git('commit', '-qm', 'Fixture repair\n\nWorker-Class: hammer');
  const headSha = git('rev-parse', 'HEAD');
  const files = to => git('diff', '--name-only', mergeBase, to).split('\n').filter(Boolean).map(filename => {
    const lines = git('diff', '--no-ext-diff', '--unified=3', mergeBase, to, '--', filename).split('\n');
    const body = lines.slice(lines.findIndex(line => line.startsWith('@@ ')));
    return { filename, status: 'modified', patch: body.join('\n'),
      additions: body.filter(line => line.startsWith('+')).length,
      deletions: body.filter(line => line.startsWith('-')).length };
  });
  const evidence = { headSha, mergeBase, primaryHead, hasHammerCommits: true,
    ciCost: { headSha, ok: true }, primaryFiles: files(primaryHead), finalFiles: files(headSha) };
  const get = async url => {
    if (url.endsWith('/pulls/1')) return { head: { sha: headSha }, base: { sha: mergeBase } };
    if (url.endsWith(`${mergeBase}...${headSha}`)) return { files: evidence.finalFiles,
      merge_base_commit: { sha: mergeBase }, total_commits: 2, commits: [
        { sha: primaryHead, commit: { message: 'Fixture author with stale output' } },
        { sha: headSha, parents: [{ sha: primaryHead }], commit: { message: 'Fixture repair\n\nWorker-Class: hammer' } },
      ] };
    if (url.endsWith(`${mergeBase}...${primaryHead}`)) return { files: evidence.primaryFiles,
      merge_base_commit: { sha: mergeBase } };
    if (url.includes('/reviews') || url.includes('/comments')) return [];
    if (url.endsWith(`/commits/${headSha}`)) return { sha: headSha, files: evidence.finalFiles };
    throw new Error(`Unexpected offline fixture read: ${url}`);
  };
  return { root, evidence, args: { repo: 'fixture/repository', prNumber: 1, headSha, get, localRepository: root } };
}

const offlineGenerator = async ({ scratch, cwd, command }) => {
  assert.deepEqual(command, ['node', 'render.mjs', '--write']);
  assert.throws(() => readFileSync(join(scratch, cwd, path)), { code: 'ENOENT' }, 'output must be removed before proof');
  execFileSync(process.execPath, command.slice(1), { cwd: join(scratch, cwd), timeout: 5000,
    env: { PATH: '/usr/bin:/bin', HOME: scratch } });
};

async function prove(f, runGeneratorImpl = offlineGenerator) {
  const refusal = checkPrimaryChange(f.evidence, f.args.headSha);
  assert.equal(refusal.reason, 'primary-change-reverted');
  const generatedBlockProofs = await proveGeneratedBlocks(f.args, f.evidence, refusal, { runGeneratorImpl });
  return { ...f.evidence, generatedBlockProofs };
}

